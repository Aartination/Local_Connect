let sharpLib: any | null | undefined;
export async function getSharp(): Promise<any | null> {
  if (sharpLib !== undefined) return sharpLib;
  try {
    sharpLib = (await import('sharp')).default;
    sharpLib.cache(false);
  } catch (e) {
    logger.warn('sharp is not available - image thumbnails disabled', e);
    sharpLib = null;
  }
  return sharpLib;
}

export async function makeImageThumbnail(
  src: string,
  thumbName: string,
): Promise<{ thumbRel: string | null; width?: number; height?: number }> {
  const sharp = await getSharp();
  if (!sharp) return { thumbRel: null };
  try {
    const img = sharp(src, { animated: false, limitInputPixels: 268402689 });
    const meta = await img.metadata();
    const thumbRel = path.join('thumbnails', thumbName);
    await sharp(src, { animated: false })
      .rotate()
      .resize(640, 640, { fit: 'inside', withoutEnlargement: true })
      .webp({ quality: 76 })
      .toFile(storagePath(thumbRel));
    const rotated = (meta.orientation ?? 1) >= 5;
    return {
      thumbRel,
      width: rotated ? meta.height : meta.width,
      height: rotated ? meta.width : meta.height,
    };
  } catch (e) {
    logger.warn('Thumbnail generation failed', e);
    return { thumbRel: null };
  }
}

/** Re-encodes an image buffer into a square avatar. Returns null if not an image. */
export async function processAvatar(input: Buffer, outFile: string): Promise<boolean> {
  const sharp = await getSharp();
  if (!sharp) {
    await fsp.writeFile(outFile, input);
    return true;
  }
  await sharp(input, { animated: false })
    .rotate()
    .resize(256, 256, { fit: 'cover' })
    .webp({ quality: 85 })
    .toFile(outFile);
  return true;
}

export async function moveFile(src: string, dest: string) {
  await fsp.mkdir(path.dirname(dest), { recursive: true });
  try {
    await fsp.rename(src, dest);
  } catch (e: any) {
    if (e.code === 'EXDEV') {
      await fsp.copyFile(src, dest);
      await fsp.unlink(src);
    } else throw e;
  }
}

export async function dirSize(dir: string): Promise<{ bytes: number; files: number }> {
  let bytes = 0;
  let files = 0;
  async function walk(d: string) {
    let entries: fs.Dirent[];
    try {
      entries = await fsp.readdir(d, { withFileTypes: true });
    } catch {
      return;
    }
    for (const e of entries) {
      const p = path.join(d, e.name);
      if (e.isDirectory()) await walk(p);
      else if (e.isFile()) {
        try {
          bytes += (await fsp.stat(p)).size;
          files++;
        } catch {
          /* vanished */
        }
      }
    }
  }
  await walk(dir);
  return { bytes, files };
}

export async function diskSpace(dir: string): Promise<{ total: number; free: number } | null> {
  try {
    const s = await fsp.statfs(dir);
    return { total: s.blocks * s.bsize, free: s.bavail * s.bsize };
  } catch {
    return null;
  }
}

