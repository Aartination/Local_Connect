import crypto from 'node:crypto';
import fs from 'node:fs';
import fsp from 'node:fs/promises';
import path from 'node:path';
import { fileTypeFromFile } from 'file-type';
import { config } from '../config.js';
import { logger } from '../logger.js';
import { badRequest } from '../utils/http.js';

/**
 * Storage layout (root = config.storageDir):
 *   images/YYYY/MM/<uuid>.<ext>     videos/...   audio/...
 *   documents/...  archives/...  other/...
 *   users/<uuid>.webp               (avatars)
 *   thumbnails/<uuid>.webp          (image + video thumbnails)
 *   tmp/<uploadId>.part             (in-progress chunked uploads)
 *   trash/<storedName>              (soft-deleted files, purge from admin)
 *
 * Every path is generated by the server. Client-provided names are only kept
 * as a sanitized display label, never used to build a filesystem path.
 */

export const STORAGE_ROOT = config.storageDir;
export const CATEGORY_DIRS: Record<string, string> = {
  IMAGE: 'images',
  VIDEO: 'videos',
  AUDIO: 'audio',
  DOCUMENT: 'documents',
  ARCHIVE: 'archives',
  OTHER: 'other',
};
export const SPECIAL_DIRS = ['users', 'thumbnails', 'tmp', 'trash'];

export function ensureStorageDirs() {
  for (const d of [...Object.values(CATEGORY_DIRS), ...SPECIAL_DIRS]) {
    fs.mkdirSync(path.join(STORAGE_ROOT, d), { recursive: true });
  }
}

/** Resolves a server-generated relative path, refusing anything outside storage. */
export function storagePath(rel: string): string {
  const abs = path.resolve(STORAGE_ROOT, rel);
  const root = path.resolve(STORAGE_ROOT);
  if (abs !== root && !abs.startsWith(root + path.sep)) {
    throw badRequest('Invalid storage path');
  }
  return abs;
}

export const tmpPath = (uploadId: string) => {
  if (!/^[a-z0-9]+$/i.test(uploadId)) throw badRequest('Invalid upload id');
  return storagePath(path.join('tmp', `${uploadId}.part`));
};

export function sanitizeFileName(name: string): string {
  let base = String(name || 'file').replace(/\\/g, '/');
  base = base.split('/').pop() || 'file';
  base = base
    .replace(/[\u0000-\u001f\u007f<>:"|?*]/g, '')
    .replace(/^\.+/, '')
    .trim();
  if (!base) base = 'file';
  if (base.length > 180) {
    const ext = path.extname(base).slice(0, 12);
    base = base.slice(0, 180 - ext.length) + ext;
  }
  return base;
}

export function extOf(name: string): string {
  return path.extname(name).replace('.', '').toLowerCase().slice(0, 10);
}

const EXT_CATEGORY: Record<string, string> = {};
const add = (cat: string, exts: string[]) => exts.forEach((e) => (EXT_CATEGORY[e] = cat));
add('IMAGE', ['jpg', 'jpeg', 'png', 'webp', 'gif', 'bmp', 'avif', 'tif', 'tiff', 'heic', 'ico']);
add('VIDEO', ['mp4', 'mov', 'webm', 'mkv', 'avi', 'm4v', '3gp', 'mpg', 'wmv']);
add('AUDIO', ['mp3', 'wav', 'ogg', 'oga', 'opus', 'm4a', 'aac', 'flac', 'weba', 'amr']);
add('DOCUMENT', [
  'pdf', 'docx', 'doc', 'xlsx', 'xls', 'pptx', 'ppt', 'odt', 'ods', 'odp', 'rtf',
  'txt', 'csv', 'md', 'json', 'log', 'epub',
]);
add('ARCHIVE', ['zip', 'rar', '7z', 'tar', 'gz', 'bz2', 'xz']);

export function categoryForExt(ext: string): string {
  return EXT_CATEGORY[ext] || 'OTHER';
}

const TEXT_EXT_MIME: Record<string, string> = {
  txt: 'text/plain; charset=utf-8',
  log: 'text/plain; charset=utf-8',
  md: 'text/markdown; charset=utf-8',
  csv: 'text/csv; charset=utf-8',
  json: 'application/json; charset=utf-8',
};

const CFB_MIME: Record<string, string> = {
  doc: 'application/msword',
  xls: 'application/vnd.ms-excel',
  ppt: 'application/vnd.ms-powerpoint',
};

/** Normalises detected extensions so they can be matched against the allow-list. */
const EXT_ALIASES: Record<string, string[]> = {
  jpg: ['jpg', 'jpeg'],
  mp4: ['mp4', 'm4v'],
  m4a: ['m4a', 'aac', 'mp4'],
  ogg: ['ogg', 'oga'],
  oga: ['ogg', 'oga'],
  opus: ['opus', 'ogg', 'oga'],
  webm: ['webm', 'weba'],
  qt: ['mov'],
  mov: ['mov'],
  gz: ['gz', 'tgz'],
};

export interface VerifiedType {
  ext: string;
  mime: string;
  category: string;
}

async function looksLikeText(file: string): Promise<boolean> {
  const fh = await fsp.open(file, 'r');
  try {
    const buf = Buffer.alloc(64 * 1024);
    const { bytesRead } = await fh.read(buf, 0, buf.length, 0);
    const slice = buf.subarray(0, bytesRead);
    if (slice.includes(0)) return false;
    try {
      // strip a possibly cut multi-byte char at the end
      new TextDecoder('utf-8', { fatal: true }).decode(slice.subarray(0, Math.max(0, bytesRead - 4)));
      return true;
    } catch {
      return false;
    }
  } finally {
    await fh.close();
  }
}

/**
 * Determines the real type of an uploaded file from its bytes.
 * Browser-provided MIME types and file extensions are never trusted.
 */
export async function verifyFileType(
  file: string,
  claimedName: string,
  allowed: string[],
  opts: { audioHint?: boolean } = {},
): Promise<VerifiedType> {
  const claimedExt = extOf(claimedName);
  const allowSet = new Set(allowed.map((e) => e.toLowerCase()));
  const detected = await fileTypeFromFile(file);

  if (detected) {
    let ext = detected.ext as string;
    let mime = detected.mime as string;

    if (ext === 'cfb') {
      // Legacy Office binary formats share one container signature.
      if (CFB_MIME[claimedExt] && allowSet.has(claimedExt)) {
        return { ext: claimedExt, mime: CFB_MIME[claimedExt], category: 'DOCUMENT' };
      }
      throw badRequest('This file type is not allowed.');
    }

    const candidates = EXT_ALIASES[ext] || [ext];
    // Prefer the user's extension when it is a valid alias of the detected type (e.g. .jpeg)
    const chosen = candidates.includes(claimedExt) ? claimedExt : candidates[0];
    if (!candidates.some((c) => allowSet.has(c))) {
      throw badRequest(`Files of type ".${ext}" are not allowed on this server.`);
    }
    if (ext === 'qt') ext = 'mov';
    ext = chosen === 'jpeg' ? 'jpeg' : chosen;
    let category = categoryForExt(ext);
    if (ext === 'webm' || ext === 'weba') {
      category = opts.audioHint || ext === 'weba' ? 'AUDIO' : 'VIDEO';
      mime = category === 'AUDIO' ? 'audio/webm' : 'video/webm';
    }
    if (ext === 'mp4' && opts.audioHint) {
      category = 'AUDIO';
      mime = 'audio/mp4';
    }
    return { ext, mime, category };
  }

  // No binary signature: allow only plain-text formats that really are text.
  if (TEXT_EXT_MIME[claimedExt] && allowSet.has(claimedExt) && (await looksLikeText(file))) {
    return { ext: claimedExt, mime: TEXT_EXT_MIME[claimedExt], category: 'DOCUMENT' };
  }
  throw badRequest('Unrecognised or disallowed file content. The file was rejected.');
}

export function newStoredName(ext: string) {
  return `${crypto.randomUUID()}.${ext}`;
}

export function relPathFor(category: string, storedName: string, date = new Date()) {
  const dir = CATEGORY_DIRS[category] || 'other';
  const y = String(date.getFullYear());
  const m = String(date.getMonth() + 1).padStart(2, '0');
  return path.join(dir, y, m, storedName);
}

export async function sha256File(file: string): Promise<string> {
  return new Promise((resolve, reject) => {
    const hash = crypto.createHash('sha256');
    fs.createReadStream(file)
      .on('data', (d) => hash.update(d))
      .on('end', () => resolve(hash.digest('hex')))
      .on('error', reject);
  });
}

